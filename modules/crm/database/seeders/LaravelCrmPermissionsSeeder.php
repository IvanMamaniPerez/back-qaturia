    public function run(): void
    {
        $registrar = app(PermissionRegistrar::class);
        $registrar->forgetCachedPermissions();

        try {
            DB::transaction(function (): void {
                $permissionNames = $this->permissionNames();

                foreach ($permissionNames as $name) {
                    Permission::firstOrCreate(
                        ['name' => $name, 'guard_name' => 'web'],
                        ['crm_permission' => true]
                    );
                }

                foreach ($this->rolePermissions($permissionNames) as $name => $permissions) {
                    $attributes = ['name' => $name, 'guard_name' => 'web'];

                    if (config('permission.teams')) {
                        $attributes[config('permission.column_names.team_foreign_key')] = null;
                    }

                    $role = Role::firstOrCreate($attributes, ['crm_role' => true]);

                    if ($role->wasRecentlyCreated || in_array($name, ['Owner', 'Admin'], true)) {
                        $role->givePermissionTo($permissions);
                    }
                }
            });
        } finally {
            $registrar->forgetCachedPermissions();
        }
    }

